def get_current_language():
    """Returns the currently configured language code ('it' or 'en')."""
    try:
        from app.system import get_settings
        settings = get_settings()
        lang = settings.get("language", DEFAULT_LANGUAGE)
        if lang in VALID_LANGUAGES:
            return lang
    except Exception as e:
        logger.debug(f"Unable to read language from settings: {e}")
    return DEFAULT_LANGUAGE

def get_translations(lang=None):
    """Returns the translation dictionary for the specified language."""
    if not lang or lang not in VALID_LANGUAGES:
        lang = get_current_language()
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])

def t(key, lang=None, **kwargs):
    """
    Translates a key into the given or active language.
    Falls back to Italian if the key is missing in English, or returns key itself.
    """
    if not lang or lang not in VALID_LANGUAGES:
        lang = get_current_language()

    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    val = lang_dict.get(key)
    if val is None and lang != DEFAULT_LANGUAGE:
        val = TRANSLATIONS[DEFAULT_LANGUAGE].get(key)
    if val is None:
        val = key

    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val
